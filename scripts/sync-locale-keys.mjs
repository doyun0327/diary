function deepMergeMissing(target, patch) {
  for (const [key, value] of Object.entries(patch)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      if (!target[key] || typeof target[key] !== 'object') target[key] = {};
      deepMergeMissing(target[key], value);
    } else if (!(key in target)) {
      target[key] = value;
    }
  }
}

function flatten(obj, prefix = '') {
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) Object.assign(out, flatten(v, key));
    else out[key] = v;
  }
  return out;
}

const en = flatten(JSON.parse(fs.readFileSync(path.join(localesDir, 'en.json'), 'utf8')));
const enKeys = Object.keys(en);

for (const [locale, patch] of Object.entries(patches)) {
  const file = path.join(localesDir, `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  deepMergeMissing(data, patch);
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`, 'utf8');

  const flat = flatten(data);
  const missing = enKeys.filter((k) => !(k in flat));
  console.log(`${locale}: merged, still missing ${missing.length}${missing.length ? ` (${missing.join(', ')})` : ''}`);
}
